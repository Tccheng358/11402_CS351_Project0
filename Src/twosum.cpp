//TwoSumArray and TwoSumHashMap implementations in C++
#include <vector>
#include <unordered_map>
#include <algorithm>

using namespace std;

// Two Sum using brute force (Array approach)
vector<int> twoSumArray(vector<int>& nums, int target) {
    for (int i = 0; i < nums.size(); i++) {
        for (int j = i + 1; j < nums.size(); j++) {
            if (nums[i] + nums[j] == target) {
                return {i, j};
            }
        }
    }
    return {};
}

// Two Sum using HashMap approach
vector<int> twoSumHashMap(vector<int>& nums, int target) {
    unordered_map<int, int> map;
    for (int i = 0; i < nums.size(); i++) {
        int complement = target - nums[i];
        if (map.find(complement) != map.end()) {
            return {map[complement], i};
        }
        map[nums[i]] = i;
    }
    return {};
}